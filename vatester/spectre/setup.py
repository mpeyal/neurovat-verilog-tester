"""Ask the user what the device is and how to drive it, before a validation.

    answers = interactive_setup(va_path, workspace, runner)     # in a terminal
    validate(va_path, answers=answers, ...)

Every question shows a suggested answer (Enter keeps it):

- the device type and the twin, detected from the .va and the twins/ folder;
- the pulse amplitudes and width, calibrated on the twin;
- for a FeFET, the read gate voltage, suggested from a Spectre Id-Vg sweep of
  the .va (the read must be where the transistor conducts), and the drain bias.

The answers are saved next to the .va as <name>.validate.json and offered
again on the next run.  Numbers accept SI suffixes: 10n, 1u, 1.5m, 50p.
"""

import json
from pathlib import Path

import numpy as np

PROFILES = ("ecfet", "memristor", "fecap", "fefet")
_SI = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3, "meg": 1e6}


def parse_number(text):
    t = text.strip().lower().rstrip("vsa")
    for suf in ("meg", "f", "p", "n", "u", "m", "k"):
        if t.endswith(suf):
            return float(t[: -len(suf)]) * _SI[suf]
    return float(t)


def config_path(va_path):
    va_path = Path(va_path)
    return va_path.with_name(va_path.stem + ".validate.json")


def load_answers(va_path):
    p = config_path(va_path)
    if p.is_file():
        try:
            return json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return None
    return None


def save_answers(va_path, answers):
    p = config_path(va_path)
    p.write_text(json.dumps(answers, indent=2) + "\n", encoding="utf-8")
    return p


def fefet_iv_sweep(dev, runner, out_dir, lo=-3.0, hi=6.0, step=0.25):
    """DC Id-Vg sweep of the .va at the drain bias -> (vg, id)."""
    from .deck import _inst_params
    va = Path(dev.va_path).name
    roles = dev.roles
    node = {roles["drain"]: "n_d", roles["gate"]: "n_g", roles["source"]: "0"}
    if "body" in roles:
        node[roles["body"]] = "0"
    for p in dev.monitors:
        node[p] = f"n_{p}"
    nodes = " ".join(node[p] for p in dev.ports)
    deck = f"""// GENERATED by NeuroVAT (vatester/spectre/setup.py): Id-Vg sweep
simulator lang=spectre
global 0
ahdl_include "{va}"
parameters vgval=0
saveOpts options save=selected
X1 ({nodes}) {dev.module}{_inst_params(dev.inst)}
vds (n_d 0) vsource dc={dev.v_ds:.12g} type=dc
vg (n_g 0) vsource dc=vgval type=dc
sweep dc param=vgval start={lo:g} stop={hi:g} step={step:g}
save X1:{roles['drain']}
"""
    sig, _ = runner({"idvg": deck}, dev.va_path, out_dir)["idvg"]
    from .psf import find_signal
    return np.asarray(sig["time"], float), np.abs(np.asarray(
        find_signal(sig, f"X1:{roles['drain']}"), float))


def suggest_read_gate(vg, idd, v_program):
    """Lowest gate voltage where the drain current reaches 10 % of its maximum
    over the sweep, kept below half the program amplitude so a read does not
    write; None if the device never conducts."""
    if not len(idd) or not np.max(idd) > 0:
        return None
    ok = np.where(idd >= 0.1 * np.max(idd))[0]
    if not len(ok):
        return None
    v = float(vg[ok[0]])
    if v_program and v > 0.5 * abs(v_program):
        v = 0.5 * abs(v_program)
    return v


def pins_text(roles):
    return ",".join(f"{k}={roles[k]}" for k in ("in", "out", "gate") if k in roles)


def parse_pins(text):
    out = {}
    for part in text.replace(";", ",").replace(" ", ",").split(","):
        if part.strip():
            k, _, v = part.partition("=")
            if not v:
                raise ValueError(f"pins need role=port pairs, got {part!r}")
            out[k.strip().lower()] = v.strip()
    return out


def _ask_pins(ask, say, ports, saved):
    """Show the ECFET pin mapping found by name; let the user confirm or set it.
    Never guessed from the order: an unmapped device must be given its pins."""
    from .deck import PinError, ecfet_roles
    try:
        roles, mon = ecfet_roles(ports, saved)
        say(f"  pins found: read channel {roles['in']} -> {roles['out']}, gate "
            f"{roles['gate']}" + (f"; monitor outputs {', '.join(mon)}" if mon else ""))
        default = pins_text(roles)
    except PinError as e:
        say(f"  {e}")
        default = ""
    while True:
        raw = ask(f"  ECFET pins (in=...,out=...,gate=...) [{default}]: ").strip()
        try:
            roles, _ = ecfet_roles(ports, parse_pins(raw) if raw else parse_pins(default))
            return roles
        except (PinError, ValueError) as e:
            say(f"    {e}")


def _ask_value(ask, say, label, default, kind=float, choices=None):
    shown = f"{default:g}" if isinstance(default, float) else str(default)
    while True:
        raw = ask(f"  {label} [{shown}]: ").strip()
        if not raw:
            return default
        try:
            if choices:
                if raw not in choices:
                    raise ValueError
                return raw
            return parse_number(raw) if kind is float else kind(raw)
        except ValueError:
            say(f"    not understood: {raw!r}" + (f" (choose {', '.join(choices)})"
                                                     if choices else ""))


def interactive_setup(va_path, workspace, runner=None, out_dir=None, ask=input, say=print,
                      saved=None):
    """Ask the questions; return the answers dict (also saved next to the .va)."""
    from .deck import va_interface
    from .suites import build_suite, profile_of
    from .twinrun import load_twin, make_model
    from .validate import Device, match_twin, shared_params

    va_path = Path(va_path)
    module, ports, va_params, bound = va_interface(
        va_path.read_text(encoding="utf-8", errors="replace"))
    say(f"{va_path.name}: module {module}({', '.join(ports)})")
    a = dict(saved or {})
    try:
        twin_default = a.get("twin") or match_twin(va_path.name, module, workspace)
    except LookupError:
        twin_default = ""
    while True:
        key = _ask_value(ask, say, "twin (key in twins/ or v1/v2/v3)", twin_default, str)
        try:
            spec = load_twin(key, workspace)
            break
        except KeyError as e:
            say(f"    {e}")
    a["twin"] = spec["key"]
    a["profile"] = _ask_value(ask, say, "device type (" + "/".join(PROFILES) + ")",
                              a.get("profile") or profile_of(spec), str, PROFILES)
    prof = a["profile"]
    params = {}
    if prof == "ecfet":
        a["pins"] = _ask_pins(ask, say, ports, a.get("pins"))
    elif prof == "fefet":
        from .deck import transistor_roles
        roles, mon = transistor_roles(ports)
        say("  pins found: " + ", ".join(f"{k} {v}" for k, v in roles.items())
            + (f"; monitor outputs {', '.join(mon)}" if mon else ""))
    if prof == "fefet":
        a["v_ds"] = _ask_value(ask, say, "drain read bias V_ds (V)", a.get("v_ds", 0.1))
    say("  probing the twin for suggested amplitudes ...")
    try:
        su = build_suite(spec, None, prof, a.get("width"), a.get("read_level"),
                         {k: a[k] for k in ("amp_pos", "amp_neg") if k in a})
        cal = su.calibration
    except RuntimeError as e:
        say(f"    the twin gave no suggestion ({e}); please enter values")
        su, cal = None, {}
    if prof == "ecfet":
        unit = "A" if spec.get("input_kind", "current") == "current" else "V"
        a["amp_pos"] = _ask_value(ask, say, f"unit gate pulse amplitude ({unit})",
                                  a.get("amp_pos", cal.get("I_unit_A",
                                                           cal.get("V_unit", 50e-12))))
        a["width"] = _ask_value(ask, say, "pulse width (s)", a.get("width", 10e-3))
    elif prof == "fecap":
        a["amp_pos"] = _ask_value(ask, say, "amplitude that switches half the polarization (V)",
                                  a.get("amp_pos", cal.get("V_half_switch", 1.0)))
        a["width"] = _ask_value(ask, say, "pulse width (s)",
                                a.get("width", cal.get("width_s", 1e-6)))
    else:
        pos = "program" if prof == "fefet" else "positive switching"
        neg = "erase" if prof == "fefet" else "negative switching"
        unit = "gate V" if prof == "fefet" else "V"
        a["amp_pos"] = _ask_value(ask, say, f"{pos} amplitude ({unit})",
                                  a.get("amp_pos", float(cal.get("V_switch_pos",
                                                                 cal.get("V_program", 1.0)))))
        a["amp_neg"] = _ask_value(ask, say, f"{neg} amplitude ({unit}, negative)",
                                  a.get("amp_neg", float(cal.get("V_switch_neg",
                                                                 cal.get("V_erase", -1.0)))))
        a["width"] = _ask_value(ask, say, "pulse width (s)",
                                a.get("width", float(cal.get("width_s", 1e-6))))
        rl = a.get("read_level", su.read_level if su else 0.1)
        if prof == "fefet" and runner is not None:
            inst = shared_params(spec, va_params)
            dev = Device("fefet", va_path, module, ports, inst, bound, a["v_ds"], spec)
            say("  running a Spectre Id-Vg sweep to find where the transistor conducts ...")
            try:
                vg, idd = fefet_iv_sweep(dev, runner, out_dir or va_path.parent)
                for v, i in zip(vg[::4], idd[::4]):
                    say(f"    Vg {v:6.2f} V   Id {i:.3e} A")
                sug = suggest_read_gate(vg, idd, a["amp_pos"])
                if sug is None:
                    say("    the transistor conducts nowhere in -3..6 V at this drain bias")
                elif "read_level" not in a:
                    rl = sug
                    say(f"    suggested read gate voltage: {sug:g} V")
            except Exception as e:          # noqa: BLE001 - a suggestion only
                say(f"    sweep failed ({e}); enter the read gate voltage yourself")
        label = "read gate voltage (V)" if prof == "fefet" else "read voltage (V)"
        a["read_level"] = _ask_value(ask, say, label, float(rl))
        if prof == "fefet":
            names = {f.name for f in __import__("dataclasses").fields(make_model(spec).p)}
            rp = a.get("twin_read_param") or ("Vread" if "Vread" in names else "")
            if rp:
                say(f"  the twin's read bias parameter '{rp}' is set to the same value")
            a["twin_read_param"] = rp
    p = save_answers(va_path, a)
    say(f"  saved to {p}")
    return a


def suggest_answers(va_path, workspace, runner=None, given=None, out_dir=None):
    """Non-interactive suggestions for a GUI form: returns (answers, notes).

    `given` holds values the user already set (twin, profile, v_ds, amp_pos,
    amp_neg, width, read_level); the rest is filled from the twin calibration
    and, for a FeFET with a runner, from a Spectre Id-Vg sweep.  notes is a
    list of lines to show (the sweep table, warnings)."""
    from .deck import va_interface
    from .suites import build_suite, profile_of
    from .twinrun import load_twin, make_model
    from .validate import Device, match_twin, shared_params

    va_path = Path(va_path)
    module, ports, va_params, bound = va_interface(
        va_path.read_text(encoding="utf-8", errors="replace"))
    a = {k: v for k, v in (given or {}).items() if v not in (None, "")}
    notes = [f"{va_path.name}: module {module}({', '.join(ports)})"]
    a["twin"] = a.get("twin") or match_twin(va_path.name, module, workspace)
    spec = load_twin(a["twin"], workspace)
    a["profile"] = a.get("profile") or profile_of(spec)
    prof = a["profile"]
    if prof == "fefet":
        a.setdefault("v_ds", 0.1)
    if prof == "ecfet":
        from .deck import PinError, ecfet_roles
        try:
            roles, mon = ecfet_roles(ports, a.get("pins"))
            a["pins"] = roles
            notes.append(f"pins: read {roles['in']} -> {roles['out']}, gate {roles['gate']}"
                         + (f"; monitors {', '.join(mon)}" if mon else ""))
        except PinError as e:
            notes.append(f"pins: {e}")
            a.pop("pins", None)
    try:
        su = build_suite(spec, None, prof, a.get("width"), a.get("read_level"),
                         {k: a[k] for k in ("amp_pos", "amp_neg") if k in a})
        cal = su.calibration
    except RuntimeError as e:
        notes.append(f"the twin gave no suggestion: {e}")
        su, cal = None, {}
    if prof == "ecfet":
        a.setdefault("amp_pos", float(cal.get("I_unit_A", cal.get("V_unit", 50e-12))))
        a.setdefault("width", 10e-3)
    elif prof == "fecap":
        a.setdefault("amp_pos", float(cal.get("V_half_switch", 1.0)))
        a.setdefault("width", float(cal.get("width_s", 1e-6)))
    else:
        a.setdefault("amp_pos", float(cal.get("V_switch_pos", cal.get("V_program", 1.0))))
        a.setdefault("amp_neg", float(cal.get("V_switch_neg", cal.get("V_erase", -1.0))))
        a.setdefault("width", float(cal.get("width_s", 1e-6)))
        if "read_level" not in a:
            a["read_level"] = float(su.read_level) if su and su.read_level is not None else 0.1
            if prof == "fefet" and runner is not None:
                inst = shared_params(spec, va_params)
                dev = Device("fefet", va_path, module, ports, inst, bound, a["v_ds"], spec)
                vg, idd = fefet_iv_sweep(dev, runner, out_dir or va_path.parent)
                notes.append("Spectre Id-Vg sweep at V_ds = %g V:" % a["v_ds"])
                notes += [f"  Vg {v:6.2f} V   Id {i:.3e} A" for v, i in zip(vg[::4], idd[::4])]
                sug = suggest_read_gate(vg, idd, a["amp_pos"])
                if sug is None:
                    notes.append("the transistor conducts nowhere in -3..6 V: "
                                 "set the read gate voltage yourself")
                else:
                    a["read_level"] = sug
                    notes.append(f"suggested read gate voltage {sug:g} V")
        if prof == "fefet":
            names = {f.name for f in __import__("dataclasses").fields(make_model(spec).p)}
            a.setdefault("twin_read_param", "Vread" if "Vread" in names else "")
    return a, notes
