"""Write a Spectre transient deck for a two-terminal Verilog-A device.

    text = make_deck("vteam.va", "vteam", stim, maxstep=1e-10,
                     params={"x_init": 0.0})

The deck instantiates `X1 (n_p 0) <module>`, drives it with the stimulus as a
PWL source (vsource for a voltage stimulus, isource into n_p for a current
stimulus), runs `tran` to the last PWL point and saves V(n_p) and the terminal
current I(X1:p).  Devices with more terminals use a hand-written deck
(`--deck` on the command line); the import and comparison are the same.
"""

import re

from .stimulus import Stimulus

ANALYSIS = "tran"
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def make_deck(va_name, module, stim: Stimulus, maxstep, params=None,
              reltol=1e-5, saves=("n_p", "X1:p"), extra_saves=(),
              pin="p"):
    """Return the text of a Spectre netlist (see the module docstring).

    va_name: the .va file name as it will sit next to the deck.
    module:  the Verilog-A module name.
    params:  instance parameter overrides {name: value}.
    pin:     the device's first terminal name (for the saved current X1:<pin>).
    """
    if not _IDENT.match(module):
        raise ValueError(f"not a Verilog-A module name: {module!r}")
    if not re.match(r"^[A-Za-z0-9_.-]+\.va$", va_name):
        raise ValueError(f"not a plain .va file name: {va_name!r}")
    inst = ""
    for k, v in (params or {}).items():
        if not _IDENT.match(k):
            raise ValueError(f"not a parameter name: {k!r}")
        inst += f" {k}={float(v):.12g}"
    save_list = list(saves)
    if pin != "p":
        save_list = [s.replace("X1:p", f"X1:{pin}") for s in save_list]
    save_list += list(extra_saves)
    for s in save_list:
        if not re.match(r"^[A-Za-z0-9_:.]+$", s):
            raise ValueError(f"not a signal name: {s!r}")
    if stim.kind == "voltage":
        src = f"vin (n_p 0) vsource type=pwl wave={stim.spectre_wave()}"
    else:
        # positive current flows from the first node through the source to the
        # second, so (0 n_p) pushes the stimulus current INTO n_p
        src = f"iin (0 n_p) isource type=pwl wave={stim.spectre_wave()}"
    return f"""// GENERATED by NeuroVAT (vatester/spectre/deck.py)
// {module} under '{stim.name}': {len(stim.t)} PWL points, t_stop {stim.t_stop:g} s,
// maxstep {maxstep:g} s.  Run:
//   spectre +escchars -format psfascii -raw {stim.name}.raw +log {stim.name}.log {stim.name}.scs

simulator lang=spectre
global 0

ahdl_include "{va_name}"

simOpts options reltol={reltol:g} vabstol=1e-9 iabstol=1e-15 gmin=1e-15
saveOpts options save=selected

X1 (n_p 0) {module}{inst}

{src}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={maxstep:.6g} errpreset=conservative
save {" ".join(save_list)}
"""


# --------------------------------------------------------------------------
# ECFET (three-terminal electrochemical transistor with a resistance readout)
# --------------------------------------------------------------------------
ECFET_OPTIONS = "reltol=1e-6 vabstol=1e-12 iabstol=1e-18 gmin=1e-15 temp=27"


def _inst_params(params):
    s = ""
    for k, v in (params or {}).items():
        if not _IDENT.match(k):
            raise ValueError(f"not a parameter name: {k!r}")
        s += f" {k}={float(v):.12g}"
    return s


def _check(va_name, module):
    if not _IDENT.match(module):
        raise ValueError(f"not a Verilog-A module name: {module!r}")
    if not re.match(r"^[A-Za-z0-9_.-]+\.va$", va_name):
        raise ValueError(f"not a plain .va file name: {va_name!r}")


V3_PORTS = ["In", "Out", "IGsc", "Rmem"]      # module ecfet_v3(In, Out, IGsc, Rmem)

_ECFET_ROLE = {
    "in": ("in", "d", "drain", "vin", "chin", "ch_in", "top", "te", "a"),
    "out": ("out", "s", "source", "vout", "chout", "ch_out", "bottom", "be", "b"),
    "gate": ("igsc", "ig", "gate", "g", "gt", "vg", "gsc", "ion", "gate_in"),
}


class PinError(ValueError):
    """The pins of a device could not be mapped; the message says how to set them."""


def ecfet_roles(ports, pins=None):
    """Map an ECFET's ports to its read-channel ends ('in', 'out') and its gate
    ('gate'); every other port is a monitor output (left on its own node).

    `pins` = {"in": port, "out": port, "gate": port} given by the user wins;
    otherwise ports are matched by name (In/D/drain, Out/S/source, IGsc/G/gate,
    any case).  Nothing is guessed from the order: an unmapped role raises
    PinError naming the ports."""
    pins = {k: v for k, v in (pins or {}).items() if v}
    by_lower = {p.lower(): p for p in ports}
    roles = {}
    for role, port in pins.items():
        if role not in _ECFET_ROLE:
            raise PinError(f"unknown ECFET pin role {role!r} (use in, out, gate)")
        if port not in ports:
            raise PinError(f"pin {port!r} is not a port of the module ({', '.join(ports)})")
        roles[role] = port
    for role, names in _ECFET_ROLE.items():
        if role in roles:
            continue
        hit = next((by_lower[n] for n in names
                    if n in by_lower and by_lower[n] not in roles.values()), None)
        if hit:
            roles[role] = hit
    missing = [r for r in ("in", "out", "gate") if r not in roles]
    if missing:
        raise PinError(
            f"cannot tell which port is the ECFET's {', '.join(missing)} among "
            f"({', '.join(ports)}); give them, e.g. pins in={ports[0]} out=... gate=...")
    if len(set(roles.values())) != 3:
        raise PinError(f"two roles share one port: {roles}")
    monitors = [p for p in ports if p not in roles.values()]
    return roles, monitors


def _ecfet_nodes(ports, roles, suffix=""):
    node = {roles["in"]: f"n_in{suffix}", roles["out"]: "0", roles["gate"]: f"n_g{suffix}"}
    for p in ports:
        node.setdefault(p, f"n_{p}{suffix}")
    return " ".join(node[p] for p in ports)


def make_ecfet_deck(va_name, module, stim: Stimulus, maxstep, params=None,
                    v_read=0.01, strobe=None, ports=None, pins=None):
    """ECFET deck: a read bias V_read across the channel (in -> out, out
    grounded), the stimulus on the gate (a current INTO the gate pin with a
    1 GOhm DC path, or a voltage), every monitor port on its own node.  Saves
    the read-source current (G = |I(vread)| / V_read, whatever the model's
    monitor pins mean) and the monitors."""
    _check(va_name, module)
    ports = list(ports or V3_PORTS)
    roles, monitors = ecfet_roles(ports, pins)
    strobe_txt = f" strobeperiod={strobe:g}" if strobe else ""
    if stim.kind == "current":
        drive = (f"// positive values flow INTO the gate pin\n"
                 f"igate (0 n_g) isource type=pwl wave={stim.spectre_wave()}\n"
                 f"Rshunt (n_g 0) resistor r=1G")
    else:
        drive = f"vgate (n_g 0) vsource type=pwl wave={stim.spectre_wave()}"
    saves = ["vread:p"] + [f"n_{m}" for m in monitors]
    return f"""// GENERATED by NeuroVAT (vatester/spectre/deck.py)
// {module} ({", ".join(ports)}): read {roles['in']}->{roles['out']}, gate {roles['gate']}
// under '{stim.name}': {len(stim.t)} PWL points, t_stop {stim.t_stop:g} s, maxstep {maxstep:g} s.

simulator lang=spectre
global 0

ahdl_include "{va_name}"

simOpts options {ECFET_OPTIONS}
saveOpts options save=selected

X1 ({_ecfet_nodes(ports, roles)}) {module}{_inst_params(params)}

vread (n_in 0) vsource dc={v_read:.12g} type=dc
{drive}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={maxstep:.6g} errpreset=conservative ic=node{strobe_txt}
save {" ".join(saves)}
"""


def make_replay_deck(va_name, module, gate_waves, t_stop, maxstep, params=None,
                     v_read=0.01, strobe=2e-4, ports=None, pins=None, kind="current"):
    """One ECFET instance per probe synapse k, each with its own read source
    vread<k> (so its current is its own) and its own recorded gate schedule
    (gate_waves[k] is a 'wave=[...]' body).  Saves vread<k>:p."""
    _check(va_name, module)
    ports = list(ports or V3_PORTS)
    roles, _ = ecfet_roles(ports, pins)
    inst = _inst_params(params)
    lines = ["// GENERATED by NeuroVAT (vatester/spectre/replay.py)",
             f"// training-schedule replay: {len(gate_waves)} {module} synapses, "
             f"t_stop {t_stop:g} s", "", "simulator lang=spectre", "global 0", "",
             f'ahdl_include "{va_name}"', "",
             f"simOpts options {ECFET_OPTIONS}", "saveOpts options save=selected"]
    saves = []
    for k, wave in enumerate(gate_waves):
        lines += ["", f"X{k} ({_ecfet_nodes(ports, roles, str(k))}) {module}{inst}",
                  f"vread{k} (n_in{k} 0) vsource dc={v_read:.12g} type=dc"]
        if kind == "current":
            lines += [f"ig{k} (0 n_g{k}) isource type=pwl wave={wave}",
                      f"Rsh{k} (n_g{k} 0) resistor r=1G"]
        else:
            lines += [f"vg{k} (n_g{k} 0) vsource type=pwl wave={wave}"]
        saves.append(f"vread{k}:p")
    lines += ["", f"{ANALYSIS} tran stop={t_stop:.12g} maxstep={maxstep:.6g} "
              f"errpreset=conservative ic=node strobeperiod={strobe:g}",
              "save " + " ".join(saves), ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Reading a .va: module, ports, parameters, $bound_step
# --------------------------------------------------------------------------
def _strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def va_interface(text):
    """-> (module, [ports], {parameter names}, bound_step parameter or None)."""
    src = _strip_comments(text)
    m = re.search(r"\bmodule\s+([A-Za-z_]\w*)\s*\(([^)]*)\)", src)
    if not m:
        raise ValueError("no 'module name(ports)' in the .va")
    ports = [p.strip() for p in m.group(2).split(",") if p.strip()]
    params = set(re.findall(r"\bparameter\s+(?:real|integer)\s+([A-Za-z_]\w*)", src))
    b = re.search(r"\$bound_step\s*\(\s*([A-Za-z_]\w*)\s*\)", src)
    bound = b.group(1) if b and b.group(1) in params else None
    return m.group(1), ports, params, bound


_ROLE = {"drain": ("d", "drain", "vdrain", "dr"), "gate": ("g", "gate", "vgate", "gt"),
         "source": ("s", "source", "vsource", "src"),
         "body": ("b", "body", "bulk", "vbody", "sub", "vbulk")}


def transistor_roles(ports):
    """Map a transistor-like port list to drain/gate/source/body (by name, else
    by position d, g, s, b); remaining ports are monitor outputs."""
    roles, left = {}, list(ports)
    for role, names in _ROLE.items():
        for p in ports:
            if p.lower() in names and p in left:
                roles[role] = p
                left.remove(p)
                break
    for role in ("drain", "gate", "source", "body"):
        if role not in roles and left and role != "body":
            roles[role] = left.pop(0)
    return roles, left


def make_fecap_deck(va_name, module, ports, stim: Stimulus, maxstep, params=None):
    """Two-terminal ferroelectric capacitor (+ optional monitor ports, e.g. a
    polarization output): voltage PWL on the first port, second grounded,
    every further port on its own node n_<port>; saves V, I and the monitors."""
    _check(va_name, module)
    if len(ports) < 2:
        raise ValueError("a capacitor needs two terminals")
    nodes = ["n_p", "0"] + [f"n_{p}" for p in ports[2:]]
    saves = ["n_p", f"X1:{ports[0]}"] + [f"n_{p}" for p in ports[2:]]
    return f"""// GENERATED by NeuroVAT (vatester/spectre/deck.py)
// {module} ({", ".join(ports)}) under '{stim.name}': t_stop {stim.t_stop:g} s

simulator lang=spectre
global 0

ahdl_include "{va_name}"

simOpts options reltol=1e-5 vabstol=1e-9 iabstol=1e-15 gmin=1e-15
saveOpts options save=selected

X1 ({" ".join(nodes)}) {module}{_inst_params(params)}

vin (n_p 0) vsource type=pwl wave={stim.spectre_wave()}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={maxstep:.6g} errpreset=conservative
save {" ".join(saves)}
"""


def make_fefet_deck(va_name, module, ports, stim: Stimulus, maxstep, params=None,
                    v_ds=0.1):
    """Ferroelectric transistor: gate-voltage PWL, drain held at V_ds, source
    and body grounded, monitor ports on their own nodes; saves the drain
    current, the gate voltage and the monitors."""
    _check(va_name, module)
    roles, mon = transistor_roles(ports)
    if not {"drain", "gate", "source"} <= set(roles):
        raise ValueError(f"cannot find drain/gate/source among ports {ports}")
    node = {roles["drain"]: "n_d", roles["gate"]: "n_g", roles["source"]: "0"}
    if "body" in roles:
        node[roles["body"]] = "0"
    for p in mon:
        node[p] = f"n_{p}"
    nodes = [node[p] for p in ports]
    saves = [f"X1:{roles['drain']}", "n_g", "n_d"] + [f"n_{p}" for p in mon]
    return f"""// GENERATED by NeuroVAT (vatester/spectre/deck.py)
// {module} ({", ".join(ports)}) under '{stim.name}': gate PWL, V_ds = {v_ds:g} V,
// t_stop {stim.t_stop:g} s

simulator lang=spectre
global 0

ahdl_include "{va_name}"

simOpts options reltol=1e-5 vabstol=1e-9 iabstol=1e-15 gmin=1e-15
saveOpts options save=selected

X1 ({" ".join(nodes)}) {module}{_inst_params(params)}

vds (n_d 0) vsource dc={v_ds:.12g} type=dc
vg (n_g 0) vsource type=pwl wave={stim.spectre_wave()}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={maxstep:.6g} errpreset=conservative
save {" ".join(saves)}
"""
