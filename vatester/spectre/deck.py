"""Write a Spectre transient deck for a two-terminal Verilog-A device.

    text = make_deck("vteam.va", "vteam", stim, maxstep=1e-10,
                     params={"x_init": 0.0})

The deck instantiates `X1 (n_p 0) <module>`, drives it with the stimulus as a
PWL source (vsource for a voltage stimulus, isource into n_p for a current
stimulus), runs `tran` to the last PWL point and saves V(n_p) and the terminal
current I(X1:p).  Devices with more terminals use a hand-written deck
(`--deck` on the command line); the import and comparison are the same.
"""

import re

from .stimulus import Stimulus

ANALYSIS = "tran"
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def make_deck(va_name, module, stim: Stimulus, maxstep, params=None,
              reltol=1e-5, saves=("n_p", "X1:p"), extra_saves=(),
              pin="p"):
    """Return the text of a Spectre netlist (see the module docstring).

    va_name: the .va file name as it will sit next to the deck.
    module:  the Verilog-A module name.
    params:  instance parameter overrides {name: value}.
    pin:     the device's first terminal name (for the saved current X1:<pin>).
    """
    if not _IDENT.match(module):
        raise ValueError(f"not a Verilog-A module name: {module!r}")
    if not re.match(r"^[A-Za-z0-9_.-]+\.va$", va_name):
        raise ValueError(f"not a plain .va file name: {va_name!r}")
    inst = ""
    for k, v in (params or {}).items():
        if not _IDENT.match(k):
            raise ValueError(f"not a parameter name: {k!r}")
        inst += f" {k}={float(v):.12g}"
    save_list = list(saves)
    if pin != "p":
        save_list = [s.replace("X1:p", f"X1:{pin}") for s in save_list]
    save_list += list(extra_saves)
    for s in save_list:
        if not re.match(r"^[A-Za-z0-9_:.]+$", s):
            raise ValueError(f"not a signal name: {s!r}")
    if stim.kind == "voltage":
        src = f"vin (n_p 0) vsource type=pwl wave={stim.spectre_wave()}"
    else:
        # positive current flows from the first node through the source to the
        # second, so (0 n_p) pushes the stimulus current INTO n_p
        src = f"iin (0 n_p) isource type=pwl wave={stim.spectre_wave()}"
    return f"""// GENERATED by NeuroVAT (vatester/spectre/deck.py)
// {module} under '{stim.name}': {len(stim.t)} PWL points, t_stop {stim.t_stop:g} s,
// maxstep {maxstep:g} s.  Run:
//   spectre +escchars -format psfascii -raw {stim.name}.raw +log {stim.name}.log {stim.name}.scs

simulator lang=spectre
global 0

ahdl_include "{va_name}"

simOpts options reltol={reltol:g} vabstol=1e-9 iabstol=1e-15 gmin=1e-15
saveOpts options save=selected

X1 (n_p 0) {module}{inst}

{src}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={maxstep:.6g} errpreset=conservative
save {" ".join(save_list)}
"""


# --------------------------------------------------------------------------
# ECFET (three-terminal electrochemical transistor with a resistance readout)
# --------------------------------------------------------------------------
ECFET_PINS = "(n_in 0 n_igsc n_rmem)"      # module ecfet_vX(In, Out, IGsc, Rmem)
ECFET_OPTIONS = "reltol=1e-6 vabstol=1e-12 iabstol=1e-18 gmin=1e-15 temp=27"


def _inst_params(params):
    s = ""
    for k, v in (params or {}).items():
        if not _IDENT.match(k):
            raise ValueError(f"not a parameter name: {k!r}")
        s += f" {k}={float(v):.12g}"
    return s


def _check(va_name, module):
    if not _IDENT.match(module):
        raise ValueError(f"not a Verilog-A module name: {module!r}")
    if not re.match(r"^[A-Za-z0-9_.-]+\.va$", va_name):
        raise ValueError(f"not a plain .va file name: {va_name!r}")


def make_ecfet_deck(va_name, module, stim: Stimulus, maxstep, params=None,
                    v_read=0.01, strobe=None):
    """Deck for an ECFET with pins (In, Out, IGsc, Rmem): a read bias V_read
    across In-Out, the stimulus as a PWL gate current flowing INTO IGsc (a 1 GOhm
    shunt gives the sense node a DC path), Rmem saved (its voltage is R in ohm,
    so G = 1/V(n_rmem))."""
    _check(va_name, module)
    if stim.kind != "current":
        raise ValueError("the ECFET gate is driven by a current stimulus")
    strobe_txt = f" strobeperiod={strobe:g}" if strobe else ""
    return f"""// GENERATED by NeuroVAT (vatester/spectre/deck.py)
// {module} (In, Out, IGsc, Rmem) under '{stim.name}': {len(stim.t)} PWL points,
// t_stop {stim.t_stop:g} s, maxstep {maxstep:g} s.

simulator lang=spectre
global 0

ahdl_include "{va_name}"

simOpts options {ECFET_OPTIONS}
saveOpts options save=selected

// Out is grounded so the In-Out read loop has a reference node
X1 {ECFET_PINS} {module}{_inst_params(params)}

vread (n_in 0) vsource dc={v_read:.12g} type=dc
// positive values flow INTO the IGsc pin
igate (0 n_igsc) isource type=pwl wave={stim.spectre_wave()}
Rshunt (n_igsc 0) resistor r=1G

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={maxstep:.6g} errpreset=conservative ic=node{strobe_txt}
save n_rmem X1:IGsc
"""


def make_replay_deck(va_name, module, gate_waves, t_stop, maxstep, params=None,
                     v_read=0.01, strobe=2e-4):
    """One ECFET instance per probe synapse k, each driven by its own recorded
    gate schedule: gate_waves[k] is a 'wave=[...]' body.  Saves n_rm<k>."""
    _check(va_name, module)
    inst = _inst_params(params)
    lines = ["// GENERATED by NeuroVAT (vatester/spectre/replay.py)",
             f"// training-schedule replay: {len(gate_waves)} {module} synapses, "
             f"t_stop {t_stop:g} s", "", "simulator lang=spectre", "global 0", "",
             f'ahdl_include "{va_name}"', "",
             f"simOpts options {ECFET_OPTIONS}", "saveOpts options save=selected", "",
             f"vread (n_in 0) vsource dc={v_read:.12g} type=dc"]
    saves = []
    for k, wave in enumerate(gate_waves):
        lines += ["",
                  f"X{k} (n_in 0 n_ig{k} n_rm{k}) {module}{inst}",
                  f"ig{k} (0 n_ig{k}) isource type=pwl wave={wave}",
                  f"Rsh{k} (n_ig{k} 0) resistor r=1G"]
        saves.append(f"n_rm{k}")
    lines += ["", f"{ANALYSIS} tran stop={t_stop:.12g} maxstep={maxstep:.6g} "
              f"errpreset=conservative ic=node strobeperiod={strobe:g}",
              "save " + " ".join(saves), ""]
    return "\n".join(lines)
