#!/usr/bin/env python
"""C5 tier 1, step 2: one Spectre deck with one ecfet_v3 instance per synapse,
each driven by its recorded write schedule as a PWL gate current.

Same DUT wiring, OPTIONS and 1 us PWL edges as the Gate A decks
(validation/spice/make_netlists.py). Every instance is set to the engine's
start state (Rinit = 1/G_start, so x_init = S^-1 of that G, pools 0) and has
A_stdp = 0, like the engine's device. maxstep = the twin's dt_max (1 ms);
a strobe (default 0.2 ms) keeps the output small (one deck holds every
synapse).

    python validation/c5/make_deck.py      # -> validation/spice/spectre_c5/v3/train.scs
"""
import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import schedule as sch  # noqa: E402

from validation.spice import make_netlists as mk  # noqa: E402

OUT = sch.ROOT / "validation" / "spice" / "spectre_c5" / "v3"


def deck(meta, per, va_dir, strobe):
    n = len(per)
    t_stop = round(meta["t_end_s"] + 0.05, 6)
    def gate(k):     # Gate A orientation: positive value flows INTO IGsc
        return " ".join(f"n_ig{k}" if nd == "n_igsc" else nd for nd in mk.GATE_NODES)

    lines = [
        "// train.scs - GENERATED by validation/c5/make_deck.py; do not edit.",
        f"// C5 tier 1: {n} ecfet_v3 synapses replaying the write pulses a NeuroVAT",
        "// stream-mode STDP run (masquelier.run, EcfetV3Array, physical time) applied;",
        f"// {meta['n_pulses']} pulses, t_stop {t_stop:g} s",
        "",
        "simulator lang=spectre",
        "global 0",
        "",
        f'ahdl_include "{va_dir}/ecfet_v3.va"',
        "",
        f"simOpts options {mk.OPTIONS}",
        "saveOpts options save=selected",
        "",
        "vread (n_in 0) vsource dc=0.01 type=dc   // one read bias for every synapse",
    ]
    saves = []
    for k in range(n):
        lines += [
            "",
            f"X{k} (n_in 0 n_ig{k} n_rm{k}) ecfet_v3 Rinit={meta['R_start_ohm']:.12g} A_stdp=0",
            f"ig{k} ({gate(k)}) isource type=pwl {sch.spectre_pwl(per[k], t_stop)}",
            f"Rsh{k} (n_ig{k} 0) resistor r=1G",
        ]
        saves += [f"n_rm{k}", f"X{k}.n_x", f"X{k}:IGsc"]
    lines += ["",
              f"tran tran stop={t_stop:.12g} maxstep={sch.DT_MAX:g} "
              f"errpreset=conservative ic=node strobeperiod={strobe:g}",
              "", "save " + " ".join(saves), ""]
    return "\n".join(lines), t_stop


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--data", default=str(sch.DATA))
    ap.add_argument("--strobe", type=float, default=2e-4)
    a = ap.parse_args(argv)
    meta, per = sch.load(a.data)
    OUT.mkdir(parents=True, exist_ok=True)
    va_dir = Path(os.path.relpath(sch.ROOT / "verilog", OUT)).as_posix()
    text, t_stop = deck(meta, per, va_dir, a.strobe)
    (OUT / "train.scs").write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {(OUT / 'train.scs').relative_to(sch.ROOT).as_posix()}: "
          f"{len(per)} synapses, {meta['n_pulses']} pulses, t_stop {t_stop:g} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
