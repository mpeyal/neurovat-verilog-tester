#!/usr/bin/env python
"""Generate the Spectre decks for the vteam-1 stimulus set.

    python validation/vteam/make_decks.py                  # deck step (100 ps)
    python validation/vteam/make_decks.py --step 1e-11     # fine-step variant
    python validation/vteam/make_decks.py --step 1e-12 --reltol 1e-6

Without --step: validation/spice/spectre_vteam/<stimulus>.scs (tracked) with
maxstep = the stimulus dt_max.  With --step <s>: the same decks with
maxstep = s (and reltol from --reltol, default 1e-6 for fine steps) written to
validation/spice/spectre_vteam_step/<tag>/ (tag e.g. 10ps, 1ps; git-ignored,
regenerate), so fine-step references never depend on editing decks on the host.
Each directory also gets run_all.sh.  The decks are GENERATED: change this
script or validation/vteam/stimuli.py, never the .scs.

Each deck: ahdl_include of verilog/vteam.va, `X1 (n_p 0) vteam` with the
stimulus' instance overrides (x_init), a PWL vsource with exactly the twin's
points, and `tran stop=<t_stop> maxstep=<step> errpreset=conservative`.
Saved: n_p, X1:p (current into p) and X1.ws (the internal state s = x/d).
"""

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from validation import common  # noqa: E402
from validation.vteam import core  # noqa: E402
from validation.vteam import stimuli as S  # noqa: E402

ANALYSIS = "tran"
RELTOL = 1e-5
FINE_RELTOL = 1e-6
OPTIONS = "vabstol=1e-9 iabstol=1e-15 gmin=1e-15"
SAVES = ["n_p", "X1:p", "X1.ws"]

GITIGNORE = """# Spectre work files (they carry host / user names); commit only scrubbed CSVs
*.raw/
*.log
*.ahdlSimDB/
*.srf
*.out
*.tran
*.csv
"""


def step_tag(step):
    """1e-11 -> '10ps', 1e-12 -> '1ps', 1e-13 -> '01ps' (as stanford ref_* sets)."""
    ps = step / S.PS
    if ps >= 1 and abs(ps - round(ps)) < 1e-9:
        return f"{int(round(ps))}ps"
    return ("0" + f"{ps:g}".split(".")[1] + "ps") if ps < 1 else f"{ps:g}ps".replace(".", "p")


def deck(stim, va, step, reltol):
    inst = " ".join(f"{k}={v:.12g}" for k, v in stim.instance_dict().items())
    return f"""// {stim.name}.scs - GENERATED by validation/vteam/make_decks.py; do not edit.
// vteam-1 validation deck: VTEAM memristor ({core.MODULE}) under '{stim.name}'
//   {stim.description}
// stimulus set {S.STIMULUS_SET_VERSION} ({S.fingerprint()[:16]}), t_stop {stim.t_stop:g} s,
// {len(stim.reads)} read plateau(s) at {S.V_READ:g} V, maxstep {step:g} s
//
// Model: S. Kvatinsky et al., "VTEAM: A General Model for Voltage-Controlled
// Memristors", IEEE TCAS-II 62(8), 2015; MemTorch 1.1.6 variant (see vteam.va).
//
// Run (writes {stim.name}.raw/{ANALYSIS}.tran.tran in PSF-ascii with Spectre 24.1):
//   spectre +escchars -format psfascii -raw {stim.name}.raw +log {stim.name}.log {stim.name}.scs
// then import with validation/vteam/scrub.py.

simulator lang=spectre
global 0

ahdl_include "{va}"

simOpts options reltol={reltol:g} {OPTIONS}
saveOpts options save=selected

X1 (n_p 0) {core.MODULE}{(" " + inst) if inst else ""}

// V(p,n): PWL with exactly the twin's points
vin (n_p 0) vsource type=pwl {stim.spectre_pwl()}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={step:g} errpreset=conservative

save {" ".join(SAVES)}
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--step", type=float, default=None,
                    help="maxstep for a fine-step variant (written to "
                         "spectre_vteam_step/<tag>/)")
    ap.add_argument("--reltol", type=float, default=None,
                    help=f"Spectre reltol (default {RELTOL:g}; {FINE_RELTOL:g} with --step)")
    ap.add_argument("--va-dir", default=None,
                    help="directory holding vteam.va as seen from the decks "
                         "(default: relative path into verilog/)")
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    if args.step is not None and args.step <= 0:
        ap.error("--step must be > 0")
    if args.out:
        out = Path(args.out)
    elif args.step is None:
        out = core.DECKS
    else:
        out = core.STEP_DECKS / step_tag(args.step)
    reltol = args.reltol or (RELTOL if args.step is None else FINE_RELTOL)
    out.mkdir(parents=True, exist_ok=True)
    va_dir = args.va_dir or Path(os.path.relpath(common.ROOT / "verilog", out)).as_posix()
    va = f"{va_dir}/{core.VA_NAME}"
    run = ["#!/bin/sh", "# GENERATED by validation/vteam/make_decks.py",
           "# Runs every vteam-1 deck with Spectre; results land next to each deck.",
           "# A failing deck is reported and the rest still run.",
           'cd "$(dirname "$0")"', "failed=''"]
    for st in S.STIMULI:
        step = st.dt_max if args.step is None else args.step
        (out / f"{st.name}.scs").write_text(deck(st, va, step, reltol), encoding="utf-8",
                                            newline="\n")
        run.append(f"spectre +escchars -format psfascii -raw {st.name}.raw "
                   f"+log {st.name}.log {st.name}.scs >/dev/null 2>&1 || "
                   f"failed=\"$failed {st.name}\"")
    run.append('[ -z "$failed" ] || { echo "FAILED decks:$failed"; exit 1; }')
    (out / "run_all.sh").write_text("\n".join(run) + "\n", encoding="utf-8", newline="\n")
    (out / ".gitignore").write_text(GITIGNORE, encoding="utf-8", newline="\n")
    shown = out.relative_to(common.ROOT).as_posix() if out.is_relative_to(common.ROOT) else out
    print(f"wrote {len(S.STIMULI)} Spectre decks + run_all.sh under {shown} "
          f"(reltol {reltol:g}, ahdl_include \"{va}\")")
    return 0


if __name__ == "__main__":
    sys.exit(main())
