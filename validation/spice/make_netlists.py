#!/usr/bin/env python
"""Generate the Spectre testbenches for the Gate A stimulus set.

Writes validation/spice/spectre/<model>/<stimulus>.scs (one deck per model and
stimulus, the whole sweep in one transient) plus run_all.sh.  The decks are
GENERATED: change this script or validation/stimuli.py, never the .scs.

    python validation/spice/make_netlists.py
    python validation/spice/make_netlists.py --va-dir /some/dir/verilog

The decks follow tools/ecfet_v3_tb.scs, with three deliberate differences:
  * the read loop is In -> ground (Out tied to node 0) so it has a reference;
  * the gate source is wired 0 -> n_igsc (GATE_NODES below) so a positive
    PWL value flows INTO the IGsc pin, i.e. I(IGsc) > 0 = potentiation.
    (SPICE/Spectre isource convention: positive current leaves the source at
    its second node.)  UNVERIFIED on a real Spectre run: the deck saves the
    terminal current X1:IGsc and compare.py refuses to score a run whose
    drive sign disagrees; regenerate with --flip-gate if single_pulse shows
    R rising;
  * Rmem is a top-level net, so it is saved as `n_rmem`, not `X1.n_rmem`;
  * vabstol is set to 1e-12: the state nodes hold conductances in volts
    (1 V == 1 S, ~1e-4 V), and Spectre's default vabstol (1 uV) would be about
    one write step - far too loose to resolve the dynamics.
"""

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from simulation_core import V2Params, V3Params  # noqa: E402
from validation import common, stimuli  # noqa: E402

GATE_NODES = ("0", "n_igsc")     # isource (p n): current flows p -> n inside
                                 # (--flip-gate swaps them; see README)
ANALYSIS = "tran"                # -> results file <stim>.raw/tran.tran
OPTIONS = ("reltol=1e-6 vabstol=1e-12 iabstol=1e-18 gmin=1e-15 temp=27")

# Signals saved by every deck.  {state} is the model's nonvolatile node.
SAVES = {
    "v2": ["n_rmem", "X1.n_nv", "X1.n_v1", "X1.n_v2", "X1.n_v3", "X1.n_stdp",
           "vread:p", "X1:IGsc"],
    "v3": ["n_rmem", "X1.n_x", "X1.n_v1", "X1.n_v2", "X1.n_v3", "X1.n_stdp",
           "vread:p", "X1:IGsc"],
}


def initial_conditions(key):
    """ic statement values, computed from the twin defaults (= .va defaults)."""
    if key == "v2":
        p = V2Params()
        g0 = min(max(1.0 / p.Rinit, p.Gmin), p.Gmax)
        return (f"ic X1.n_nv={g0:.12g} X1.n_v1=0 X1.n_v2=0 X1.n_v3=0",
                "n_nv = 1/Rinit (also forced by the .va's analysis(\"ic\") branch)")
    p = V3Params()
    x0 = p.x_of_G(min(max(1.0 / p.Rinit, p.Gmin), p.Gmax))
    return (f"// no ic statement: x_init = {x0:.9f} (from Rinit)",
            "n_x and the pools are idt(rate, ic) nodes seeded inside the .va")


def deck(key, st, va_dir, gate_nodes=GATE_NODES):
    _f, va_rel, module = common.MODELS[key]
    va = f"{va_dir}/{Path(va_rel).name}"
    ic, ic_note = initial_conditions(key)
    p, n = gate_nodes
    return f"""// {st.name}.scs - GENERATED by validation/spice/make_netlists.py; do not edit.
// Gate A validation deck: {module} under stimulus '{st.name}'
//   {st.description}
// stimulus set {stimuli.STIMULUS_SET_VERSION} ({stimuli.fingerprint()[:16]}), t_stop {st.t_stop:g} s
//
// Run (writes {st.name}.raw/{ANALYSIS}.tran in PSF-ascii):
//   spectre +escchars -format psfascii -raw {st.name}.raw +log {st.name}.log {st.name}.scs
// then import with validation/scrub_spectre.py (see validation/README.md).

simulator lang=spectre
global 0

ahdl_include "{va}"

simOpts options {OPTIONS}
saveOpts options save=selected

// DUT: module {module}(In, Out, IGsc, Rmem); defaults = Python twin defaults.
// Out is grounded so the In-Out read loop has a reference node.
X1 (n_in 0 n_igsc n_rmem) {module}

// read path: 10 mV across In-Out; i(vread) = V_read * G
vread (n_in 0) vsource dc={common.V_READ:g} type=dc

// gate drive: intended so a positive value flows INTO the IGsc pin (potentiation)
igate ({p} {n}) isource type=pwl {st.spectre_pwl()}
Rshunt (n_igsc 0) resistor r=1G   // DC path for the IGsc sense node

// initial state ({ic_note})
{ic}

{ANALYSIS} tran stop={st.t_stop:.12g} maxstep={st.dt_max:g} errpreset=conservative ic=node

save {" ".join(SAVES[key])}
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--va-dir", default=None,
                    help="directory holding ecfet_v2.va / ecfet_v3.va as seen "
                         "from the deck (default: relative path into verilog/)")
    ap.add_argument("--out", default=str(common.SPECTRE_DECKS))
    ap.add_argument("--model", default="all")
    ap.add_argument("--flip-gate", action="store_true",
                    help="wire the gate source n_igsc -> 0 (as tools/ecfet_v3_tb.scs) "
                         "if the single_pulse check shows R rising")
    args = ap.parse_args(argv)
    gate = GATE_NODES[::-1] if args.flip_gate else GATE_NODES

    out = Path(args.out)
    run_lines = ["#!/bin/sh", "# GENERATED by validation/spice/make_netlists.py",
                 "# Runs every Gate A deck with Spectre; results land next to each deck.",
                 "set -e", 'cd "$(dirname "$0")"']
    count = 0
    for key in common.model_keys(args.model):
        d = out / key
        d.mkdir(parents=True, exist_ok=True)
        va_dir = args.va_dir or Path(os.path.relpath(common.ROOT / "verilog", d)).as_posix()
        run_lines.append(f"( cd {key} &&")
        for st in stimuli.STIMULI:
            (d / f"{st.name}.scs").write_text(deck(key, st, va_dir, gate),
                                              encoding="utf-8", newline="\n")
            run_lines.append(f"  spectre +escchars -format psfascii -raw {st.name}.raw "
                             f"+log {st.name}.log {st.name}.scs &&")
            count += 1
        run_lines.append("  true )")
    (out / "run_all.sh").write_text("\n".join(run_lines) + "\n", encoding="utf-8",
                                    newline="\n")
    print(f"wrote {count} Spectre decks + run_all.sh under "
          f"{out.relative_to(common.ROOT).as_posix() if out.is_relative_to(common.ROOT) else out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
