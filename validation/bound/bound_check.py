#!/usr/bin/env python
"""v3 at the x rails: twin vs Spectre (the bound step-collapse check).

The old ecfet_v3.va gated the write off with a hard switch at x = 0 / 1
while retention kept pulling x back, so Spectre chattered on the upper rail
and its step collapsed to ~1e-10 s (a 190 s Sharbati LTP/LTD deck ran 9.5 h
and wrote 207 GB without finishing).  The .va now tapers the outward write
over the last `x_soft` of the window.  These decks drive v3 INTO each rail,
hold it there under continued drive, and come back off it, and score the twin
against Spectre with the Gate A rule (NRMSE <= 1 %, max <= 3 % of range).

    python validation/bound/bound_check.py decks            # write the decks
    # run them with Spectre (spectre +escchars -format psfascii -raw <n>.raw +log <n>.log <n>.scs)
    python validation/bound/bound_check.py scrub <dir>      # <dir>/<n>.raw/tran.tran.tran + <n>.log
    python validation/bound/bound_check.py score            # table + data/bound/summary.csv

Each stimulus sets its own Rinit (on the X1 instance line and in the twin).
"""

import argparse
import csv
import hashlib
import json
import math
import os
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from simulation_core import EcfetV3, V3Params  # noqa: E402
from validation import common, compare, scrub_spectre as ss, stimuli  # noqa: E402
from validation.spice import make_netlists as mk  # noqa: E402

SET_VERSION = "bound-1"
DECKS = common.ROOT / "validation" / "spice" / "spectre_bound" / "v3"
DATA = common.DATA / "bound"
FIGS = common.FIGURES / "bound"
PERIOD, WIDTH, T0 = 50e-3, 10e-3, 0.1


def _train(name, desc, rinit, phases, dt_max=5e-3, tail=0.2):
    """phases: [(n_pulses, amp_A), ...] at one pulse every PERIOD."""
    pulses, k = [], 0
    for n, amp in phases:
        for _ in range(n):
            pulses.append((round(T0 + k * PERIOD, 6), WIDTH, amp))
            k += 1
    t_stop = round(T0 + k * PERIOD + tail, 6)
    return stimuli.Stimulus(name, desc, tuple(pulses), t_stop=t_stop,
                            dt_max=dt_max, params={"Rinit": rinit})


def build():
    return [
        _train("hi_short", "reproduction: Rinit 872 ohm, 30 x +50 pA into the upper rail",
               872.0, [(30, 50e-12)]),
        _train("hi_50pA", "Rinit 880 ohm: 120 x +50 pA (rail from pulse ~62), "
               "then 40 x -50 pA off the rail", 880.0, [(120, 50e-12), (40, -50e-12)]),
        _train("hi_500pA", "Rinit 900 ohm: 30 x +500 pA (rail from pulse ~7), "
               "then 20 x -500 pA", 900.0, [(30, 500e-12), (20, -500e-12)]),
        _train("lo_50pA", "Rinit 8000 ohm: 120 x -50 pA into the lower rail, "
               "then 40 x +50 pA", 8000.0, [(120, -50e-12), (40, 50e-12)]),
        _train("lo_500pA", "Rinit 8000 ohm: 30 x -500 pA into the lower rail, "
               "then 20 x +500 pA", 8000.0, [(30, -500e-12), (20, 500e-12)]),
    ]


STIMULI = build()
BY_NAME = {s.name: s for s in STIMULI}


def fingerprint():
    blob = json.dumps({"version": SET_VERSION,
                       "stimuli": [s.as_dict() for s in STIMULI]},
                      sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


# --------------------------------------------------------------------------
def deck(st, va_dir):
    p, n = mk.GATE_NODES
    return f"""// {st.name}.scs - GENERATED by validation/bound/bound_check.py; do not edit.
// v3 rail check: {st.description}
// stimulus set {SET_VERSION} ({fingerprint()[:16]}), t_stop {st.t_stop:g} s

simulator lang=spectre
global 0

ahdl_include "{va_dir}/ecfet_v3.va"

simOpts options {mk.OPTIONS}
saveOpts options save=selected

X1 (n_in 0 n_igsc n_rmem) ecfet_v3 Rinit={st.params['Rinit']:g}
vread (n_in 0) vsource dc={common.V_READ:g} type=dc
igate ({p} {n}) isource type=pwl {st.spectre_pwl()}
Rshunt (n_igsc 0) resistor r=1G

{mk.ANALYSIS} tran stop={st.t_stop:.12g} maxstep={st.dt_max:g} errpreset=conservative ic=node

save {" ".join(mk.SAVES["v3"])}
"""


def write_decks():
    DECKS.mkdir(parents=True, exist_ok=True)
    va_dir = Path(os.path.relpath(common.ROOT / "verilog", DECKS)).as_posix()
    for st in STIMULI:
        (DECKS / f"{st.name}.scs").write_text(deck(st, va_dir), encoding="utf-8",
                                              newline="\n")
    print(f"wrote {len(STIMULI)} decks to {DECKS.relative_to(common.ROOT).as_posix()}")


# --------------------------------------------------------------------------
def twin(st):
    model = EcfetV3(V3Params(Rinit=st.params["Rinit"]))
    ts = common.base_grid(st)
    raw = common.simulate_on_grid(model, st.waveform(), ts)
    return common.twin_columns("v3", ts, raw)


def scrub(src_dir):
    DATA.mkdir(parents=True, exist_ok=True)
    for st in STIMULI:
        src = Path(src_dir) / f"{st.name}.raw" / "tran.tran.tran"
        if not src.is_file():
            continue
        sig, info = ss.read_psf_ascii(src.read_text(encoding="utf-8", errors="replace"))
        cols, measured = ss.to_canonical("v3", sig, st)
        if cols["t_s"][-1] < st.t_stop * (1 - 1e-6):
            raise SystemExit(f"{st.name}: transient stops at {cols['t_s'][-1]:g} s")
        prov = (f"# source: {ss.version_tag(info)}; model: v3; stimulus_set: "
                f"{SET_VERSION} {fingerprint()[:16]}")
        lines = [prov, ",".join(common.COLUMNS)]
        data = np.column_stack([np.asarray(cols[c], float) for c in common.COLUMNS])
        lines += [",".join("nan" if math.isnan(v) else f"{v:.10g}" for v in row)
                  for row in data]
        ss.check_clean(lines)
        log = src.parent.parent / f"{st.name}.log"
        wall = ss.wall_from_log(log.read_text(encoding="utf-8", errors="replace")) \
            if log.is_file() else None
        dest = DATA / f"{st.name}.csv"
        dest.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        common.write_meta(dest.with_suffix(".json"), {
            "source": ss.version_tag(info), "model": "v3", "stimulus": st.name,
            "stimulus_set": SET_VERSION, "n_points": int(len(cols["t_s"])),
            "drive_measured": bool(measured),
            "wall_s": None if wall is None else round(float(wall), 4)})
        print("wrote", dest.relative_to(common.ROOT).as_posix())


def score(figures=True):
    rows = []
    for st in STIMULI:
        rp = DATA / f"{st.name}.csv"
        if not rp.is_file():
            continue
        tw = twin(st)
        ref, _ = common.read_csv(rp)
        meta = common.read_meta(rp.with_suffix(".json"))
        tg = compare.common_grid(tw["t_s"], ref["t_s"])
        g_t = np.interp(tg, tw["t_s"], tw["G_S"])
        g_r = np.interp(tg, ref["t_s"], ref["G_S"])
        m = compare.metrics(g_t, g_r)
        dchk = compare.drive_check(tw, ref)
        v = compare.verdict(m) if dchk == "ok" else "FAIL"
        x_ref = np.interp(tg, ref["t_s"], ref["x_Li"])
        rows.append({"stimulus": st.name, "Rinit_ohm": st.params["Rinit"],
                     "n_pulses": len(st.pulses), "nrmse_pct": 100 * m["nrmse"],
                     "maxerr_pct": 100 * m["maxerr"], "g_range_uS": 1e6 * m["range"],
                     "x_ref_min": float(np.min(x_ref)), "x_ref_max": float(np.max(x_ref)),
                     "spectre_points": meta.get("n_points"),
                     "spectre_wall_s": meta.get("wall_s"), "drive_check": dchk,
                     "verdict": v})
        if figures:
            compare.overlay(FIGS / f"v3_{st.name}.png",
                            f"v3 {st.name}: twin vs spectre  NRMSE {100*m['nrmse']:.3f}%"
                            f"  max {100*m['maxerr']:.3f}%  [{v}]",
                            tg, [("twin", g_t, "tab:blue")], "spectre", g_r)
    if rows:
        DATA.mkdir(parents=True, exist_ok=True)
        with open(DATA / "summary.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
            w.writeheader()
            for r in rows:
                w.writerow({k: (f"{v:.6g}" if isinstance(v, float) else v)
                            for k, v in r.items()})
    print(f"{'stimulus':10s} {'NRMSE%':>8s} {'max%':>8s} {'range uS':>9s} "
          f"{'x_max':>12s} {'points':>7s} {'wall s':>7s}  verdict")
    for r in rows:
        print(f"{r['stimulus']:10s} {r['nrmse_pct']:8.4f} {r['maxerr_pct']:8.4f} "
              f"{r['g_range_uS']:9.2f} {r['x_ref_max']:12.9f} {r['spectre_points']:7d} "
              f"{r['spectre_wall_s'] or float('nan'):7.3f}  {r['verdict']} ({r['drive_check']})")
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["decks", "scrub", "score"])
    ap.add_argument("src", nargs="?")
    a = ap.parse_args(argv)
    if a.cmd == "decks":
        write_decks()
    elif a.cmd == "scrub":
        scrub(a.src)
    else:
        rows = score()
        return 0 if rows and all(r["verdict"] == "PASS" for r in rows) else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
