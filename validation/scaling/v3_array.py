#!/usr/bin/env python
"""C3 benchmark 1: N independent ECFET v3 synapses, twin vs Spectre, wall
time against N, on one machine.

Workload: the C5 tier-1 write schedule (validation/data/c5/schedule.csv:
16 synapses, 3608 calibrated 10 ms gate pulses of 0.2-1563 pA over 4.06 s,
from a NeuroVAT stream-mode STDP run). Device k replays synapse (k mod 16)'s
pulses, so every device gets a realistic training schedule and the total
pulse count grows linearly with N (~225 pulses per device). Pulses start on
the engine's 10 ms write-window grid, as in a real training run.

Sides (each single-threaded):

- ``spectre``: one deck, N ``ecfet_v3`` instances, each with its own PWL
  gate source (Gate A options, maxstep 1 ms, 1 us edges, strobe 1 ms; the
  C5 deck generator's wiring). Only the read node of the first min(N, 16)
  instances is saved.
- ``scalar``: the scalar twin ``EcfetV3`` per device on the Gate A time grid
  (refined at every pulse edge, dt_max 1 ms) - the twin that passed Gate A,
  in a Python loop over devices.
- ``scalar_engine``: the engine's scalar adapter ``ScalarTwinArray`` in
  physical time, full read, ``program`` at each write time and ``peek``
  every 1 ms (the network's call pattern).
- ``vector``: the vectorised ``EcfetV3Array`` (from ``vector_twin_factory``)
  with the same call pattern as ``scalar_engine``.

Accuracy (same probes): each twin against Spectre on Spectre's 1 ms strobe
grid, Gate A rule on G (NRMSE <= 1 %, max <= 3 % of the device's Spectre G
range).

    python validation/scaling/v3_array.py bench --n 1 4 16 64 256 1024 \
        --sides spectre vector scalar scalar_engine --reps 3 --out results/scaling/v3
"""
import argparse
import json
import math
import os
import statistics
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path[:0] = [str(HERE), str(ROOT / "src"), str(ROOT), str(ROOT / "validation" / "c5")]
import machine  # noqa: E402,F401  (sets the thread env before numpy)

import numpy as np  # noqa: E402

import schedule as sch  # noqa: E402

N_BASE = 16
PROBES = 16
STROBE = 1e-3
READ = 1e-3


def workload():
    meta, per = sch.load()
    t_stop = round(meta["t_end_s"] + 0.05, 6)
    return meta, per, t_stop


def pulses_of(per, n):
    return [per[k % N_BASE] for k in range(n)]


# ----------------------------------------------------------------- Spectre
def deck_text(meta, per_dev, t_stop, va_dir, title):
    """One ecfet_v3 instance per entry of ``per_dev`` (its pulse list)."""
    from validation.spice import make_netlists as mk
    n = len(per_dev)

    def gate(k):
        return " ".join(f"n_ig{k}" if nd == "n_igsc" else nd for nd in mk.GATE_NODES)
    lines = [
        "// GENERATED by validation/scaling; do not edit.",
        f"// C3 scaling: {n} independent ecfet_v3 instances; {title}",
        f"// t_stop {t_stop:g} s",
        "", "simulator lang=spectre", "global 0", "",
        f'ahdl_include "{va_dir}/ecfet_v3.va"', "",
        f"simOpts options {mk.OPTIONS}", "saveOpts options save=selected", "",
        "vread (n_in 0) vsource dc=0.01 type=dc"]
    pw = {}
    for k, pulses in enumerate(per_dev):
        key = id(pulses)
        if key not in pw:
            pw[key] = sch.spectre_pwl(pulses, t_stop)
        lines += [f"X{k} (n_in 0 n_ig{k} n_rm{k}) ecfet_v3 "
                  f"Rinit={meta['R_start_ohm']:.12g} A_stdp=0",
                  f"ig{k} ({gate(k)}) isource type=pwl {pw[key]}",
                  f"Rsh{k} (n_ig{k} 0) resistor r=1G"]
    saves = [f"n_rm{k}" for k in range(min(n, PROBES))]
    lines += ["", f"tran tran stop={t_stop:.12g} maxstep={sch.DT_MAX:g} "
              f"errpreset=conservative ic=node strobeperiod={STROBE:g}",
              "", "save " + " ".join(saves), ""]
    return "\n".join(lines)


def save_deck(text, f):
    f = Path(f)
    f.parent.mkdir(parents=True, exist_ok=True)
    with open(f, "w", encoding="utf-8", newline="\n") as fh:     # py3.9
        fh.write(text)
    return f


def va_dir_for(out_dir):
    return Path(os.path.relpath(ROOT / "verilog", Path(out_dir))).as_posix()


def write_deck(n, out_dir):
    meta, per, t_stop = workload()
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    text = deck_text(meta, pulses_of(per, n), t_stop, va_dir_for(out_dir),
                     f"instance k replays C5 synapse (k mod {N_BASE})'s write pulses")
    return save_deck(text, out_dir / f"v3_n{n}.scs")


def read_probes(tran_file, n):
    from validation import scrub_spectre as ss
    sig, _ = ss.read_psf_ascii(Path(tran_file).read_text(encoding="utf-8",
                                                          errors="replace"))
    norm = {ss._norm(k): v for k, v in sig.items()}
    t = np.asarray(sig["time"], float)
    G = np.stack([1.0 / np.asarray(norm[ss._norm(f"n_rm{k}")], float)
                  for k in range(min(n, PROBES))])
    return t, G


# ----------------------------------------------------------------- twins
def run_scalar(meta, per, n, t_stop):
    """Scalar twin per device, Gate A grid. -> probes [(t, G)]."""
    probes = []
    for k, pulses in enumerate(pulses_of(per, n)):
        ts, G, _, _ = sch.replay(meta, pulses, t_stop)
        if k < PROBES:
            probes.append((ts, G))
    return probes


def _events(per, n):
    """Pulses of all devices grouped by start tick: [(tick, cols, amps)]."""
    rows = []
    for k, pulses in enumerate(pulses_of(per, n)):
        for s, w, a in pulses:
            if w != pulses[0][1]:
                raise ValueError("one pulse width expected")
            rows.append((s, k, a))
    rows.sort()
    ev, i = [], 0
    while i < len(rows):
        j = i
        while j < len(rows) and rows[j][0] == rows[i][0]:
            j += 1
        ev.append((rows[i][0], np.array([r[1] for r in rows[i:j]], np.int64),
                   np.array([r[2] for r in rows[i:j]], float)))
        i = j
    return ev, per[0][0][1] * sch.TICK


def run_engine_path(dev, meta, per, n, t_stop, prepared=None):
    """program at every write time, peek every 1 ms (Synapses' pattern)."""
    ev, width = prepared or _events(per, n)
    dev.set_conductance(np.full(dev.shape, meta["g_start_S"]))
    n_reads = int(math.floor(t_stop / READ + 1e-9))
    step = int(round(READ / sch.TICK))
    t_r = np.arange(n_reads + 1) * READ
    out = np.empty((n_reads + 1, min(n, PROBES)))
    out[0] = np.asarray(dev.peek(0.0), float).ravel()[:PROBES]
    j = 0
    zeros = {}
    for r in range(1, n_reads + 1):
        rt = r * step
        while j < len(ev) and ev[j][0] <= rt:
            tick, cols, amps = ev[j]
            z = zeros.get(len(cols))
            if z is None:
                z = zeros[len(cols)] = np.zeros(len(cols), np.int64)
            dev.program(z, cols, amps, width, tick * sch.TICK)
            j += 1
        out[r] = np.asarray(dev.peek(t_r[r]), float).ravel()[:PROBES]
    return [(t_r, out[:, k]) for k in range(out.shape[1])]


def make_dev(kind, n):
    from neurovat.devices import ScalarTwinArray, vector_twin_factory
    from simulation_core.model_v3 import EcfetV3, V3Params
    meta = workload()[0]
    p = V3Params(**meta["v3_params"])
    if kind == "vector":
        fac = vector_twin_factory(lambda: EcfetV3(p), "physical", "full")
        if fac.kind != "vector":
            raise SystemExit("vector_twin_factory fell back to the scalar adapter")
        return fac(1, n)
    return ScalarTwinArray(lambda: EcfetV3(p), 1, n, "physical", "full")


def time_twin(side, n, reps):
    meta, per, t_stop = workload()
    walls, probes = [], None
    for _ in range(reps):
        if side == "scalar":
            t0 = time.perf_counter()
            probes = run_scalar(meta, per, n, t_stop)
        else:
            prep = _events(per, n)
            dev = make_dev(side.replace("scalar_engine", "scalar"), n)
            t0 = time.perf_counter()
            probes = run_engine_path(dev, meta, per, n, t_stop, prep)
        walls.append(time.perf_counter() - t0)
    return walls, probes


# ----------------------------------------------------------------- accuracy
def accuracy(t_sp, G_sp, probes):
    """Gate A rule per probe, on Spectre's strobe grid."""
    res = []
    for k, (ts, G) in enumerate(probes):
        g_tw = np.interp(t_sp, ts, G)
        e = g_tw - G_sp[k]
        rng = float(G_sp[k].max() - G_sp[k].min())
        nr = math.sqrt(float(np.mean(e * e))) / rng
        mx = float(np.max(np.abs(e))) / rng
        res.append({"device": k, "nrmse_pct": 100 * nr, "max_pct": 100 * mx,
                    "pass": bool(nr <= 0.01 and mx <= 0.03)})
    return {"probes": len(res), "pass": sum(r["pass"] for r in res),
            "nrmse_pct_max": max(r["nrmse_pct"] for r in res),
            "max_pct_max": max(r["max_pct"] for r in res)}


def summary(walls):
    w = sorted(x for x in walls if x is not None)
    if not w:
        return {"median_s": None, "min_s": None, "max_s": None}
    return {"median_s": statistics.median(w), "min_s": w[0], "max_s": w[-1]}


# ----------------------------------------------------------------- driver
def bench(a):
    from spectre_run import run as sp_run
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    meta, per, t_stop = workload()
    spectre_dead = False                  # a timeout: skip every larger N
    for n in a.n:
        rec = {"benchmark": "v3_array", "n": n, "t_stop_s": t_stop,
               "commit": a.commit,
               "pulses": sum(len(p) for p in pulses_of(per, n)), "sides": {}}
        spectre_probes = None
        if "spectre" in a.sides and spectre_dead:
            rec["sides"]["spectre"] = {"skipped": "a smaller N timed out",
                                       "timed_out": True}
        elif "spectre" in a.sides and n <= a.spectre_max:
            deck = write_deck(n, out / "decks")
            runs = []
            for r in range(a.reps):
                info = machine.info()
                res = sp_run(deck, keep_raw=(r == 0), timeout=a.timeout)
                res["machine"] = info
                if r == 0 and "raw" in res:
                    spectre_probes = read_probes(res.pop("raw"), n)
                    from spectre_run import cleanup
                    cleanup(deck)
                runs.append(res)
                print(f"spectre n={n} rep {r}: tran {res['tran_elapsed_s']} s, "
                      f"total {res['total_elapsed_s']} s, wall {res['wall_s']:.2f} s, "
                      f"steps {res['accepted_steps']}, load {info['loadavg_1_5_15']}",
                      flush=True)
                if res["timed_out"]:
                    break
            rec["sides"]["spectre"] = {
                "runs": runs,
                "tran": summary([x["tran_elapsed_s"] for x in runs]),
                "total": summary([x["total_elapsed_s"] for x in runs]),
                "wall": summary([x["wall_s"] for x in runs]),
                "timed_out": any(x["timed_out"] for x in runs)}
            spectre_dead = rec["sides"]["spectre"]["timed_out"]
            if spectre_probes is not None:
                np.savez_compressed(out / f"spectre_probes_n{n}.npz",
                                    t=spectre_probes[0], G=spectre_probes[1])
        for side in a.sides:
            if side == "spectre":
                continue
            if side.startswith("scalar") and n > a.scalar_max:
                continue
            info = machine.info()
            walls, probes = time_twin(side, n, a.reps)
            s = {"walls_s": walls, **summary(walls), "machine": info}
            if spectre_probes is not None:
                s["accuracy"] = accuracy(spectre_probes[0], spectre_probes[1], probes)
            rec["sides"][side] = s
            print(f"{side} n={n}: median {s['median_s']:.3f} s "
                  f"({min(walls):.3f}-{max(walls):.3f}) load {info['loadavg_1_5_15']}"
                  + (f" acc {s['accuracy']}" if "accuracy" in s else ""), flush=True)
        (out / f"v3_n{n}.json").write_text(json.dumps(rec, indent=1) + "\n",
                                           encoding="utf-8")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("bench")
    b.add_argument("--n", type=int, nargs="+", default=[1, 4, 16, 64, 256, 1024])
    b.add_argument("--sides", nargs="+",
                   default=["spectre", "vector", "scalar", "scalar_engine"])
    b.add_argument("--reps", type=int, default=3)
    b.add_argument("--scalar-max", type=int, default=1024)
    b.add_argument("--spectre-max", type=int, default=100000)
    b.add_argument("--timeout", type=float, default=900.0)
    b.add_argument("--out", default=str(ROOT / "results" / "scaling" / "v3"))
    b.add_argument("--commit", default="", help="code commit, recorded")
    d = sub.add_parser("deck")
    d.add_argument("--n", type=int, required=True)
    d.add_argument("--out", default=str(ROOT / "results" / "scaling" / "v3" / "decks"))
    a = ap.parse_args(argv)
    if a.cmd == "deck":
        print(write_deck(a.n, a.out))
        return 0
    return bench(a)


if __name__ == "__main__":
    sys.exit(main())
