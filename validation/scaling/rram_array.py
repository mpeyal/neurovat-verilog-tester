#!/usr/bin/env python
"""C3 benchmark 2: N independent two-terminal devices (Stanford-PKU RRAM,
VTEAM), twin vs Spectre, wall time against N, on one machine.

Each of the N instances gets its own PWL voltage source with the same
validation stimulus (the stanford-1 / vteam-1 deck of that name: same
options, instance parameters and PWL points as validation/<model>/
make_decks.py). The twins have no vectorised array, so the twin side is the
scalar twin in a Python loop over the devices (``core.run_twin``, the run
that passed against the fine-step Spectre reference).

Spectre step: the step must be fine enough to pass against the 1 ps Spectre
reference (validation/data/<model>/step_convergence_ref_1ps.csv):

- Stanford ``pulse_set_ref`` (+1.8 V / 100 ns SET): 100 ps FAILS (I NRMSE
  4.6 %), 10 ps passes (0.84 %); the reference itself is 1 ps. Timed at
  10 ps and 1 ps (``--step``; the .va's time_step bound = maxstep).
- VTEAM ``on_train``: the 100 ps deck step passes; timed at 100 ps.

Accuracy on the array: instance 0's current against the twin's (I NRMSE,
% of the current range) and its read conductance at the read plateaus.

    python validation/scaling/rram_array.py --model stanford --stimulus pulse_set_ref \
        --step 1e-11 --n 1 4 16 64 --reps 3
"""
import argparse
import json
import math
import os
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path[:0] = [str(HERE), str(ROOT)]
import machine  # noqa: E402,F401

import numpy as np  # noqa: E402

PROBES = 1


def _mods(model):
    if model == "stanford":
        from validation.stanford import core, make_decks as md, stimuli as S
        return core, md, S
    from validation.vteam import core, make_decks as md, stimuli as S
    return core, md, S


def deck_text(model, st, n, step, va):
    core, md, S = _mods(model)
    if model == "stanford":
        P = core.twin_module().StanfordPKUParams()
        vals = {"model_switch": 0, "q": P.q, "kb": P.kb, "time_step": step}
        vals.update(st.instance_dict())
        inst = " ".join(f"{k}={v:.12g}" for k, v in vals.items())
        opts = md.OPTIONS
        node, term = "n_te", "TE"
    else:
        inst = " ".join(f"{k}={v:.12g}" for k, v in st.instance_dict().items())
        opts = f"reltol={md.RELTOL:g} {md.OPTIONS}"
        node, term = "n_p", "p"
    pwl = st.spectre_pwl()
    lines = ["// GENERATED by validation/scaling/rram_array.py; do not edit.",
             f"// C3 scaling: {n} independent {core.MODULE} instances under "
             f"'{st.name}', maxstep {step:g} s", "",
             "simulator lang=spectre", "global 0", "", f'ahdl_include "{va}"', "",
             f"simOpts options {opts}", "saveOpts options save=selected", ""]
    for k in range(n):
        lines += [f"X{k} ({node}{k} 0) {core.MODULE} {inst}".rstrip(),
                  f"v{k} ({node}{k} 0) vsource type=pwl {pwl}"]
    lines += ["", f"tran tran stop={st.t_stop:.12g} maxstep={step:g} "
              "errpreset=conservative", "",
              "save " + " ".join(f"{node}{k} X{k}:{term}" for k in range(min(n, PROBES))),
              ""]
    return "\n".join(lines)


def va_path(model, deck_dir):
    core = _mods(model)[0]
    name = "stanford_pku_rram_spectre.va" if model == "stanford" else core.VA_NAME
    return Path(os.path.relpath(ROOT / "verilog" / name, deck_dir)).as_posix()


def probes(tran_file, model):
    from validation import scrub_spectre as ss
    sig, _ = ss.read_psf_ascii(Path(tran_file).read_text(encoding="utf-8",
                                                          errors="replace"))
    norm = {ss._norm(k): np.asarray(v, float) for k, v in sig.items()}
    node, term = ("n_te0", "X0:TE") if model == "stanford" else ("n_p0", "X0:p")
    return np.asarray(sig["time"], float), norm[ss._norm(node)], norm[ss._norm(term)]


def accuracy(model, st, cols, t, v, i):
    core = _mods(model)[0]
    it = cols["I_TE_A"] if "I_TE_A" in cols else cols[[k for k in cols if k.startswith("I_")][0]]
    i_sp = np.interp(cols["t_s"], t, i)
    i_sp = -i_sp if np.dot(i_sp, it) < 0 else i_sp      # terminal-current sign
    e = it - i_sp
    rng = float(i_sp.max() - i_sp.min())
    out = {"i_nrmse_pct": 100 * math.sqrt(float(np.mean(e * e))) / rng,
           "i_max_pct": 100 * float(np.max(np.abs(e))) / rng}
    tr = np.asarray(st.read_times, float)
    if len(tr):
        vk = [k for k in cols if k.startswith("V_")][0]
        g_tw = np.interp(tr, cols["t_s"], it) / np.interp(tr, cols["t_s"], cols[vk])
        g_sp = np.interp(tr, cols["t_s"], i_sp) / np.interp(tr, t, v)
        out["g_read_max_pct"] = 100 * float(np.max(np.abs(g_tw - g_sp) / np.abs(g_sp)))
    return out


def main(argv=None):
    from spectre_run import cleanup, run as sp_run
    from v3_array import summary
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--model", choices=["stanford", "vteam"], required=True)
    ap.add_argument("--stimulus", required=True)
    ap.add_argument("--step", type=float, required=True)
    ap.add_argument("--n", type=int, nargs="+", default=[1, 4, 16, 64])
    ap.add_argument("--reps", type=int, default=3)
    ap.add_argument("--timeout", type=float, default=900.0)
    ap.add_argument("--no-twin", action="store_true")
    ap.add_argument("--commit", default="")
    ap.add_argument("--out", default=str(ROOT / "results" / "scaling" / "rram"))
    a = ap.parse_args(argv)
    core, md, S = _mods(a.model)
    st = [s for s in S.STIMULI if s.name == a.stimulus][0]
    out = Path(a.out)
    decks = out / "decks"
    decks.mkdir(parents=True, exist_ok=True)
    tag = f"{a.model}_{a.stimulus}_{a.step:.0e}"
    dead = False
    for n in a.n:
        rec = {"benchmark": "rram_array", "model": a.model, "stimulus": a.stimulus,
               "spectre_maxstep_s": a.step, "twin_dt_max_s": st.dt_max, "n": n,
               "t_stop_s": st.t_stop, "commit": a.commit, "sides": {}}
        twin_cols = None
        if not a.no_twin:
            walls = []
            mi = machine.info()
            for _ in range(a.reps):
                t0 = time.perf_counter()
                for _k in range(n):
                    cols, _, _ = core.run_twin(st)
                walls.append(time.perf_counter() - t0)
                twin_cols = cols
            rec["sides"]["twin_scalar"] = {"walls_s": walls, **summary(walls),
                                           "machine": mi}
            print(f"{tag} twin n={n}: {summary(walls)}", flush=True)
        if dead:
            rec["sides"]["spectre"] = {"skipped": "a smaller N timed out", "timed_out": True}
        else:
            d = decks / f"{tag}_n{n}.scs"
            with open(d, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(deck_text(a.model, st, n, a.step, va_path(a.model, decks)))
            runs, acc = [], None
            for r in range(a.reps):
                mi = machine.info()
                res = sp_run(d, keep_raw=(r == 0), timeout=a.timeout)
                res["machine"] = mi
                if "raw" in res:
                    t, v, i = probes(res.pop("raw"), a.model)
                    cleanup(d)
                    if twin_cols is None:
                        twin_cols, _, _ = core.run_twin(st)
                    acc = accuracy(a.model, st, twin_cols, t, v, i)
                runs.append(res)
                print(f"{tag} spectre n={n} rep {r}: tran {res['tran_elapsed_s']} s, "
                      f"total {res['total_elapsed_s']} s, steps {res['accepted_steps']}, "
                      f"load {mi['loadavg_1_5_15']}", flush=True)
                if res["timed_out"]:
                    break
            rec["sides"]["spectre"] = {
                "runs": runs, "tran": summary([x["tran_elapsed_s"] for x in runs]),
                "total": summary([x["total_elapsed_s"] for x in runs]),
                "timed_out": any(x["timed_out"] for x in runs),
                "probe0_twin_vs_spectre": acc}
            dead = rec["sides"]["spectre"]["timed_out"]
            print(f"{tag} n={n} accuracy {acc}", flush=True)
        (out / f"{tag}_n{n}.json").write_text(json.dumps(rec, indent=1) + "\n",
                                              encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
