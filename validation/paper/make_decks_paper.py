#!/usr/bin/env python
"""Generate the Spectre decks for the sharbati-1 stimulus set.

Writes validation/spice/spectre_sharbati/<model>/<stimulus>.scs, run_all.sh,
run_first.sh (v3 sp_pot only - the gate orientation check) and a .gitignore
for the Spectre work files.  Same DUT wiring, OPTIONS, saved signals and
initial conditions as the Gate A decks (validation/spice/make_netlists.py);
only the stimulus, its fingerprint and the maxstep differ.

    python validation/paper/make_decks_paper.py
    python validation/paper/make_decks_paper.py --flip-gate      # if R rises on sp_pot
    python validation/paper/make_decks_paper.py --va-dir /some/dir/verilog

The retention deck uses ONE transient with maxstep = 60 s (the twin's coarse
hold step) and relies on the PWL breakpoints plus Spectre's LTE control around
the programming pulse; no piecewise-maxstep syntax is emitted.
"""

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from validation import common  # noqa: E402
from validation.paper import core  # noqa: E402
from validation.paper import sharbati_stimuli as S  # noqa: E402
from validation.spice import make_netlists as mk  # noqa: E402

GITIGNORE = """# Spectre work files (they carry host / user names); commit only scrubbed CSVs
**/*.raw/
**/*.log
**/*.ahdlSimDB/
**/*.srf
**/*.out
**/*.tran
**/*.csv
"""


def deck(key, st, va_dir, gate_nodes=mk.GATE_NODES):
    _f, va_rel, module = common.MODELS[key]
    va = f"{va_dir}/{Path(va_rel).name}"
    ic, ic_note = mk.initial_conditions(key)
    p, n = gate_nodes
    hold = ""
    if st.params.get("grid_segments"):
        hold = ("// maxstep = the twin's coarse hold step; the twin uses "
                f"{st.params['grid_segments'][0][1]:g} s steps up to "
                f"{st.params['grid_segments'][0][0]:g} s.\n")
    return f"""// {st.name}.scs - GENERATED by validation/paper/make_decks_paper.py; do not edit.
// Paper overlay deck ({S.PAPER}): {module} under '{st.name}'
//   {st.description}
// stimulus set {S.STIMULUS_SET_VERSION} ({S.fingerprint()[:16]}), t_stop {st.t_stop:g} s
//
// Run (writes {st.name}.raw/{mk.ANALYSIS}.tran in PSF-ascii):
//   spectre +escchars -format psfascii -raw {st.name}.raw +log {st.name}.log {st.name}.scs
// then import with validation/paper/scrub_paper.py (see validation/README.md).

simulator lang=spectre
global 0

ahdl_include "{va}"

simOpts options {mk.OPTIONS}
saveOpts options save=selected

// DUT: module {module}(In, Out, IGsc, Rmem); defaults = Python twin defaults.
X1 (n_in 0 n_igsc n_rmem) {module}

// read path: {common.V_READ*1e3:g} mV across In-Out (the paper reads at 0.1 V; the
// models' state does not depend on the read bias)
vread (n_in 0) vsource dc={common.V_READ:g} type=dc

// gate drive: intended so a positive value flows INTO the IGsc pin (potentiation)
igate ({p} {n}) isource type=pwl {st.spectre_pwl()}
Rshunt (n_igsc 0) resistor r=1G   // DC path for the IGsc sense node

// initial state ({ic_note})
{ic}

{hold}{mk.ANALYSIS} tran stop={st.t_stop:.12g} maxstep={st.dt_max:g} errpreset=conservative ic=node

save {" ".join(mk.SAVES[key])}
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--va-dir", default=None)
    ap.add_argument("--out", default=str(core.DECKS))
    ap.add_argument("--model", default="all")
    ap.add_argument("--flip-gate", action="store_true",
                    help="wire the gate source n_igsc -> 0 if v3 sp_pot shows R rising")
    args = ap.parse_args(argv)
    gate = mk.GATE_NODES[::-1] if args.flip_gate else mk.GATE_NODES
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    run = ["#!/bin/sh", "# GENERATED by validation/paper/make_decks_paper.py",
           "# Runs every sharbati-1 deck with Spectre; results land next to each deck.",
           "set -e", 'cd "$(dirname "$0")"']
    count = 0
    for key in common.model_keys(args.model):
        d = out / key
        d.mkdir(parents=True, exist_ok=True)
        va_dir = args.va_dir or Path(os.path.relpath(common.ROOT / "verilog", d)).as_posix()
        run.append(f"( cd {key} &&")
        for st in S.STIMULI:
            (d / f"{st.name}.scs").write_text(deck(key, st, va_dir, gate),
                                              encoding="utf-8", newline="\n")
            run.append(f"  spectre +escchars -format psfascii -raw {st.name}.raw "
                       f"+log {st.name}.log {st.name}.scs &&")
            count += 1
        run.append("  true )")
    (out / "run_all.sh").write_text("\n".join(run) + "\n", encoding="utf-8", newline="\n")
    (out / "run_first.sh").write_text(
        "#!/bin/sh\n# GENERATED: gate-orientation check. R must FALL at t = 5 s "
        "(about 4400 -> 4370 ohm).\n# If it rises, regenerate with --flip-gate before "
        "running run_all.sh.\nset -e\ncd \"$(dirname \"$0\")/v3\"\n"
        "spectre +escchars -format psfascii -raw sp_pot.raw +log sp_pot.log sp_pot.scs\n",
        encoding="utf-8", newline="\n")
    (out / ".gitignore").write_text(GITIGNORE, encoding="utf-8", newline="\n")
    shown = out.relative_to(common.ROOT).as_posix() if out.is_relative_to(common.ROOT) else out
    print(f"wrote {count} Spectre decks + run_all.sh + run_first.sh under {shown}"
          f"{'  (gate flipped)' if args.flip_gate else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
