#!/usr/bin/env python
"""Generate the Spectre decks for the stanford-1 stimulus set.

Writes validation/spice/spectre_stanford/<stimulus>.scs, run_all.sh,
run_first.sh and a .gitignore for the Spectre work files.  The decks are
GENERATED: change this script or validation/stanford/stimuli.py, never the .scs.

    python validation/stanford/make_decks.py
    python validation/stanford/make_decks.py --va-dir /some/dir/verilog
    python validation/stanford/make_decks.py --patched   # see "Spectre syntax" below

Each deck: ahdl_include of the Stanford .va, `X1 (n_te 0) rram_v_1_0_0` with
the twin's parameters (q and kb passed EXPLICITLY, because the .va defaults
them to the simulator's own `P_Q / `P_K, which differ between constants.vams
versions), a PWL vsource TE->ground with exactly the twin's points, and

    tran stop=<t_stop> maxstep=<dt_max> errpreset=conservative

with the instance parameter time_step (the .va's $bound_step) set to the same
dt_max.  For the 8.1 ms HSPICE-template DC sweeps that replaces the default
1 ns bound (8 million steps) by 1 us; switching is then resolved by Spectre's
own error control.

Spectre syntax (unverified, flagged): the official file is written for HSPICE
and uses comma ranges such as `from[0, 1]` / `from(390, 460)` (standard
Verilog-A is `from[0:1]`) and two `include directives on one line.  If
Spectre's AHDL parser rejects them, run with --patched: it writes
verilog/stanford_pku_rram_spectre.va (git-ignored like the original) with only
those two textual fixes, a modification note, and the copyright notices kept,
and points the decks at it.
"""

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from validation import common  # noqa: E402
from validation.stanford import core  # noqa: E402
from validation.stanford import stimuli as S  # noqa: E402

ANALYSIS = "tran"
OPTIONS = "reltol=1e-5 vabstol=1e-9 iabstol=1e-15 gmin=1e-15"
SAVES = ["n_te", "X1:TE", "vte:p"]
FIRST = "pulse_reset_ref"
RUN_LAST = ("dc_reset_ref", "dc_set_ref")
PATCHED_NAME = "stanford_pku_rram_spectre.va"

GITIGNORE = """# Spectre work files (they carry host / user names); commit only scrubbed CSVs
*.raw/
*.log
*.ahdlSimDB/
*.srf
*.out
*.tran
*.csv
"""

_RANGE = re.compile(r"(\bfrom\s*)([\[(])\s*([^,\[\]()]+?)\s*,\s*([^,\[\]()]+?)\s*([\])])")


def patch_source(text):
    """Only the two syntax fixes; everything else (notices included) is kept."""
    text = text.replace('`include "constants.vams"`include "disciplines.vams"',
                        '`include "constants.vams"\n`include "disciplines.vams"')
    text = _RANGE.sub(lambda m: f"{m.group(1)}{m.group(2)}{m.group(3)}:{m.group(4)}{m.group(5)}",
                      text)
    note = ("// MODIFIED for Spectre by NeuroVAT validation/stanford/make_decks.py:\n"
            "// comma parameter ranges -> colon ranges, the two `include directives on\n"
            "// separate lines.  No equation or value changed.\n")
    return note + text


def instance_params(stim):
    P = core.twin_module().StanfordPKUParams()
    vals = {"model_switch": 0, "q": P.q, "kb": P.kb, "time_step": stim.dt_max}
    vals.update(stim.instance_dict())
    return " ".join(f"{k}={v:.12g}" for k, v in vals.items())


def deck(stim, va):
    reads = len(stim.reads)
    return f"""// {stim.name}.scs - GENERATED by validation/stanford/make_decks.py; do not edit.
// stanford-1 validation deck: Stanford-PKU RRAM v1.0.0 ({core.MODULE}) under '{stim.name}'
//   {stim.description}
// stimulus set {S.STIMULUS_SET_VERSION} ({S.fingerprint()[:16]}), t_stop {stim.t_stop:g} s,
// {reads} read plateau(s) at {S.V_READ:g} V
//
// Model: Stanford Nanoelectronics Research Group (Prof. H.-S. Philip Wong);
// Z. Jiang et al., IEEE TED 63(5), 2016; nanoHUB doi:10.4231/D37H1DN48.
//
// Run (writes {stim.name}.raw/{ANALYSIS}.tran in PSF-ascii):
//   spectre +escchars -format psfascii -raw {stim.name}.raw +log {stim.name}.log {stim.name}.scs
// then import with validation/stanford/scrub.py (see validation/README.md).

simulator lang=spectre
global 0

ahdl_include "{va}"

simOpts options {OPTIONS}
saveOpts options save=selected

// DUT: module {core.MODULE}(TE, BE); parameters = twin defaults, q/kb explicit,
// time_step ($bound_step) = maxstep
X1 (n_te 0) {core.MODULE} {instance_params(stim)}

// V(TE,BE): PWL with exactly the twin's points
vte (n_te 0) vsource type=pwl {stim.spectre_pwl()}

{ANALYSIS} tran stop={stim.t_stop:.12g} maxstep={stim.dt_max:g} errpreset=conservative

save {" ".join(SAVES)}
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--va-dir", default=None,
                    help="directory holding the .va as seen from the decks "
                         "(default: relative path into verilog/)")
    ap.add_argument("--out", default=str(core.DECKS))
    ap.add_argument("--patched", action="store_true",
                    help=f"write verilog/{PATCHED_NAME} (range/include syntax fixes) "
                         "and use it")
    args = ap.parse_args(argv)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    va_name = core.VA_NAME
    if args.patched:
        if not core.VA_PATH.is_file():
            raise SystemExit(f"{core.VA_PATH} not found (download it first, see README)")
        src = core.VA_PATH.read_text(encoding="utf-8", errors="strict")
        (core.VA_PATH.parent / PATCHED_NAME).write_text(patch_source(src), encoding="utf-8",
                                                        newline="\n")
        va_name = PATCHED_NAME
    va_dir = args.va_dir or Path(os.path.relpath(common.ROOT / "verilog", out)).as_posix()
    va = f"{va_dir}/{va_name}"
    run = ["#!/bin/sh", "# GENERATED by validation/stanford/make_decks.py",
           "# Runs every stanford-1 deck with Spectre; results land next to each deck.",
           "# A failing deck is reported and the rest still run.  The two 8.1 ms",
           "# HSPICE-template DC decks (1 us step bound) run last: they are the most",
           "# likely to hit Spectre step-control trouble on the RESET slide.",
           'cd "$(dirname "$0")"', "failed=''"]
    for st in S.STIMULI:
        (out / f"{st.name}.scs").write_text(deck(st, va), encoding="utf-8", newline="\n")
    for st in sorted(S.STIMULI, key=lambda s: s.name in RUN_LAST):
        run.append(f"spectre +escchars -format psfascii -raw {st.name}.raw "
                   f"+log {st.name}.log {st.name}.scs || failed=\"$failed {st.name}\"")
    run.append('[ -z "$failed" ] || { echo "FAILED decks:$failed"; exit 1; }')
    (out / "run_all.sh").write_text("\n".join(run) + "\n", encoding="utf-8", newline="\n")
    (out / "run_first.sh").write_text(
        "#!/bin/sh\n# GENERATED: smoke test. Checks the .va compiles in Spectre and the\n"
        "# current sign: during the -1.3 V pulse X1:TE must be NEGATIVE (about -35 mA at\n"
        "# t = 1 ns, falling in magnitude as the gap opens), and the 0.1 V read at\n"
        "# ~170 ns must give about +6.6 uA (G_read ~ 66 uS).\n"
        f"set -e\ncd \"$(dirname \"$0\")\"\n"
        f"spectre +escchars -format psfascii -raw {FIRST}.raw +log {FIRST}.log {FIRST}.scs\n",
        encoding="utf-8", newline="\n")
    (out / ".gitignore").write_text(GITIGNORE, encoding="utf-8", newline="\n")
    shown = out.relative_to(common.ROOT).as_posix() if out.is_relative_to(common.ROOT) else out
    print(f"wrote {len(S.STIMULI)} Spectre decks + run_all.sh + run_first.sh under {shown}"
          f"  (ahdl_include \"{va}\")")
    return 0


if __name__ == "__main__":
    sys.exit(main())
